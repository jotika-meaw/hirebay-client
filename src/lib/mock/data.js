function booking({
  id,
  eq,
  customer,
  startDate,
  endDate,
  quantity,
  days,
  units,
  totalAmount,
  phone,
  address,
  notes = "",
  status,
  paymentStatus,
  bookedAt,
  transactionId = null,
  checkoutSessionId = null,
  holdExpiresAt = null,
}) {
  const item = equipment.find((e) => e.id === eq);
  const user = users.find((u) => u.id === customer);
  return {
    id,
    equipmentId: eq,
    equipment: {
      name: item.name,
      image: item.image,
      category: item.category,
      rentalType: item.rentalType,
      price: item.price,
    },
    owner: { ...item.owner },
    customer: {
      id: user.id,
      name: user.name,
      email: user.email,
      image: user.image,
    },
    startDate,
    endDate,
    quantity,
    days,
    units,
    totalAmount,
    phone,
    address,
    notes,
    status,
    paymentStatus,
    holdExpiresAt,
    checkoutSessionId,
    transactionId,
    createdAt: bookedAt,
    updatedAt: bookedAt,
  };
}

